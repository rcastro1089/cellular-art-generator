export function parseDigits(str){
  const set = new Set();
  for (const ch of str) if (ch >= '0' && ch <= '8') set.add(+ch);
  return [...set].sort();
}

export function parse3dCounts(str){
  const out = new Set();
  for (const tok of String(str).split(/[^0-9]+/)){
    if (!tok) continue;
    const v = +tok;
    if (v <= 26) out.add(v);
    else for (const ch of tok) out.add(+ch);   // "56" stays {5,6} via comma; "456" → digits
  }
  return [...out].sort((a, b) => a - b);
}

